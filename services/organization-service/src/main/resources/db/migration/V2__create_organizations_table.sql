CREATE TABLE organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(150) NOT NULL,

    slug VARCHAR(100) NOT NULL UNIQUE,

    description VARCHAR(500),

    organization_type VARCHAR(30) NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    created_by_user_id BIGINT NOT NULL,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_organization_type
        CHECK (organization_type IN ('BUSINESS', 'NON_PROFIT', 'OTHER')),

    CONSTRAINT chk_organization_status
        CHECK (status IN ('ACTIVE', 'SUSPENDED'))
);

CREATE INDEX idx_organizations_created_by_user_id
    ON organizations(created_by_user_id);
